"""
Adversarial Training (PGD-based).

Based on Madry et al. (2018): "Towards Deep Learning Models Resistant to Adversarial Attacks"
https://arxiv.org/abs/1706.06083
"""

import torch
import torch.nn as nn
from typing import Dict

from .base import BaseTrainer
from attacks.pgd import PGDAttack


class AdversarialTrainer(BaseTrainer):
    """
    Adversarial training using PGD attacks.
    
    Reference: Madry et al. (2018)
    
    Key idea: Train on adversarial examples generated by PGD attack
    to make the model robust to worst-case perturbations.
    
    min_θ E[(x,y)~D] [max_{δ: ||δ||≤ε} L(f_θ(x+δ), y)]
    """
    
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        
        # Create PGD attacker
        self.attacker = PGDAttack(
            model=self.model,
            epsilon=self.config.attack.epsilon,
            alpha=self.config.attack.alpha,
            num_steps=self.config.attack.num_steps,
            random_start=self.config.attack.random_start
        )
        
        print(f"[Adversarial Training] epsilon={self.config.attack.epsilon:.4f}, "
              f"alpha={self.config.attack.alpha:.4f}, steps={self.config.attack.num_steps}")
    
    def train_step(self, images: torch.Tensor, labels: torch.Tensor) -> Dict[str, float]:
        """Adversarial training step."""
        # Generate adversarial examples
        self.model.eval()  # Eval mode for attack generation
        adv_images = self.attacker(images, labels)
        
        # Train on adversarial examples
        self.model.train()
        self.optimizer.zero_grad()
        
        if self.config.training.use_amp and self.scaler is not None:
            with torch.cuda.amp.autocast():
                outputs = self.model(adv_images)
                loss = self.criterion(outputs, labels)
            
            self.scaler.scale(loss).backward()
            self.scaler.step(self.optimizer)
            self.scaler.update()
        else:
            outputs = self.model(adv_images)
            loss = self.criterion(outputs, labels)
            loss.backward()
            self.optimizer.step()
        
        # Compute accuracy on adversarial examples
        with torch.no_grad():
            preds = outputs.argmax(dim=1)
            correct = (preds == labels).sum().item()
            
            # Also track clean accuracy
            clean_outputs = self.model(images)
            clean_preds = clean_outputs.argmax(dim=1)
            clean_correct = (clean_preds == labels).sum().item()
        
        return {
            "loss": loss.item(),
            "correct": correct,
            "clean_correct": clean_correct
        }
    
    def train_epoch(self) -> Dict[str, float]:
        """Train for one epoch with additional metrics."""
        self.model.train()
        total_loss = 0
        adv_correct = 0
        clean_correct = 0
        total = 0
        
        debug_mode = self.config.training.debug
        max_batches = self.config.training.debug_batches if debug_mode else float('inf')
        
        for batch_idx, (images, labels) in enumerate(self.train_loader):
            if batch_idx >= max_batches:
                break
            
            images = images.to(self.device)
            labels = labels.to(self.device)
            
            metrics = self.train_step(images, labels)
            
            total_loss += metrics["loss"]
            adv_correct += metrics["correct"]
            clean_correct += metrics.get("clean_correct", metrics["correct"])
            total += labels.size(0)
            
            self.global_step += 1
            
            if batch_idx % self.config.log_interval == 0:
                print(f"  Batch {batch_idx}: Loss={metrics['loss']:.4f}, "
                      f"Adv Acc={metrics['correct']/labels.size(0):.4f}")
        
        avg_loss = total_loss / min(len(self.train_loader), max_batches)
        adv_accuracy = adv_correct / total
        clean_accuracy = clean_correct / total
        
        return {
            "loss": avg_loss,
            "accuracy": adv_accuracy,
            "clean_accuracy": clean_accuracy
        }


class TRADESTrainer(BaseTrainer):
    """
    TRADES: TRadeoff-inspired Adversarial DEfense via Surrogate-loss minimization.
    
    Reference: Zhang et al. (2019) "Theoretically Principled Trade-off between 
    Robustness and Accuracy"
    
    Loss = CE(f(x), y) + β * KL(f(x) || f(x+δ))
    """
    
    def __init__(self, *args, beta: float = 6.0, **kwargs):
        super().__init__(*args, **kwargs)
        
        self.beta = beta
        self.attacker = PGDAttack(
            model=self.model,
            epsilon=self.config.attack.epsilon,
            alpha=self.config.attack.alpha,
            num_steps=self.config.attack.num_steps
        )
        
        print(f"[TRADES Training] beta={self.beta}")
    
    def train_step(self, images: torch.Tensor, labels: torch.Tensor) -> Dict[str, float]:
        """TRADES training step."""
        batch_size = images.size(0)
        
        # Generate adversarial examples (maximize KL divergence)
        self.model.eval()
        
        # Use KL divergence as attack objective
        images_adv = images.clone().detach()
        images_adv.requires_grad = True
        
        with torch.no_grad():
            clean_logits = self.model(images)
        
        for _ in range(self.config.attack.num_steps):
            adv_logits = self.model(images_adv)
            kl_loss = nn.KLDivLoss(reduction='batchmean')(
                torch.log_softmax(adv_logits, dim=1),
                torch.softmax(clean_logits, dim=1)
            )
            kl_loss.backward()
            
            grad = images_adv.grad.detach()
            images_adv = images_adv.detach() + self.config.attack.alpha * grad.sign()
            images_adv = torch.clamp(images_adv, images - self.config.attack.epsilon, 
                                     images + self.config.attack.epsilon)
            images_adv = torch.clamp(images_adv, 0, 1)
            images_adv.requires_grad = True
        
        images_adv = images_adv.detach()
        
        # TRADES loss
        self.model.train()
        self.optimizer.zero_grad()
        
        clean_logits = self.model(images)
        adv_logits = self.model(images_adv)
        
        # Natural loss
        nat_loss = self.criterion(clean_logits, labels)
        
        # Robust loss (KL divergence)
        rob_loss = nn.KLDivLoss(reduction='batchmean')(
            torch.log_softmax(adv_logits, dim=1),
            torch.softmax(clean_logits.detach(), dim=1)
        )
        
        loss = nat_loss + self.beta * rob_loss
        loss.backward()
        self.optimizer.step()
        
        with torch.no_grad():
            preds = clean_logits.argmax(dim=1)
            correct = (preds == labels).sum().item()
        
        return {
            "loss": loss.item(),
            "nat_loss": nat_loss.item(),
            "rob_loss": rob_loss.item(),
            "correct": correct
        }
